package migrate

import (
	"context"
	"fmt"
	"io"
	"strings"

	"github.com/jackc/pgx/v5"
)

// schemaReferenceHeader opens doc/003-schema-reference.sql. The file is
// read by people and agents writing SQL, so it says what it is and where
// it comes from before the first table.
const schemaReferenceHeader = `-- GENERATED by ` + "`proto-migrate schema-reference`" + `. Do not edit.
--
-- The public schema a database built only by src/api-srv/sql/migrations/
-- ends up with: bin/510-reset-test-db rewrites this file after ` + "`up`" + ` on
-- an empty scratch database, and bin/300-run-tests go fails when the
-- committed copy differs. Read it for table and column names (doc/900);
-- change the schema only with a new migration.
--
-- Tables and indexes sorted by name; columns in table order. SERIAL stands
-- for an integer column with a nextval() default. Primary keys and UNIQUE
-- constraints show as their indexes. schema_migration (the migrator's own
-- table) is left out.
`

// WriteSchemaReference prints the public schema of the database conn is
// connected to as CREATE TABLE / CREATE INDEX text, from
// information_schema and pg_indexes. Output depends only on the schema, so
// two databases built by the same migrations print the same bytes.
func WriteSchemaReference(ctx context.Context, conn *pgx.Conn,
	w io.Writer) error {
	var version int
	var name string
	if err := conn.QueryRow(ctx, `
		SELECT version, name
		FROM schema_migration
		ORDER BY version DESC
		LIMIT 1`).Scan(&version, &name); err != nil {
		return fmt.Errorf("schema-reference: no applied migration "+
			"(run up first): %w", err)
	}

	var out strings.Builder
	out.WriteString(schemaReferenceHeader)
	fmt.Fprintf(&out, "--\n-- Through migration %04d_%s.\n", version, name)

	tableList, err := pgx.CollectRows(queryRows(ctx, conn, `
		SELECT table_name::text
		FROM information_schema.tables
		WHERE table_schema = 'public'
		  AND table_type = 'BASE TABLE'
		  AND table_name <> 'schema_migration'
		ORDER BY table_name`), pgx.RowTo[string])
	if err != nil {
		return fmt.Errorf("schema-reference: tables: %w", err)
	}

	for _, table := range tableList {
		columnList, err := pgx.CollectRows(queryRows(ctx, conn, `
			SELECT column_name::text, data_type::text, udt_name::text,
			       is_nullable::text,
			       character_maximum_length::int,
			       numeric_precision::int, numeric_scale::int,
			       column_default::text
			FROM information_schema.columns
			WHERE table_schema = 'public' AND table_name = $1
			ORDER BY ordinal_position`, table),
			pgx.RowToStructByPos[schemaColumn])
		if err != nil {
			return fmt.Errorf("schema-reference: %s columns: %w", table,
				err)
		}
		lineList := make([]string, 0, len(columnList))
		for _, column := range columnList {
			lineList = append(lineList, "    "+column.definition())
		}
		fmt.Fprintf(&out, "\nCREATE TABLE %s (\n%s\n);\n", table,
			strings.Join(lineList, ",\n"))

		indexList, err := pgx.CollectRows(queryRows(ctx, conn, `
			SELECT indexdef
			FROM pg_indexes
			WHERE schemaname = 'public' AND tablename = $1
			ORDER BY indexname`, table), pgx.RowTo[string])
		if err != nil {
			return fmt.Errorf("schema-reference: %s indexes: %w", table,
				err)
		}
		for _, index := range indexList {
			out.WriteString(index + ";\n")
		}
	}
	_, err = io.WriteString(w, out.String())
	return err
}

// queryRows is conn.Query for pgx.CollectRows: pgx returns a failed query
// as Rows in an error state, and CollectRows reports that error, so the
// one from Query is redundant here.
func queryRows(ctx context.Context, conn *pgx.Conn, sql string,
	args ...any) pgx.Rows {
	rows, _ := conn.Query(ctx, sql, args...)
	return rows
}

// schemaColumn is one information_schema.columns row.
type schemaColumn struct {
	Name       string
	DataType   string
	UdtName    string
	IsNullable string
	CharLength *int32
	Precision  *int32
	Scale      *int32
	Default    *string
}

// udtNameList maps the internal names an array's element type carries to
// the names a migration is written with.
var udtNameList = map[string]string{
	"int2": "smallint", "int4": "integer", "int8": "bigint",
	"float4": "real", "float8": "double precision", "bool": "boolean",
	"varchar": "varchar", "numeric": "numeric",
}

// definition is the column as one CREATE TABLE line, without indent.
func (c schemaColumn) definition() string {
	line := c.Name + " " + c.typeName()
	if c.Default != nil {
		if strings.HasPrefix(*c.Default, "nextval(") {
			line = c.Name + " SERIAL"
		} else {
			// doc/900 allows no DEFAULT on application data; show one
			// rather than hide it.
			line += " DEFAULT " + *c.Default
		}
	}
	if c.IsNullable == "NO" {
		line += " NOT NULL"
	}
	return line
}

func (c schemaColumn) typeName() string {
	switch c.DataType {
	case "ARRAY":
		element := strings.TrimPrefix(c.UdtName, "_")
		if name, ok := udtNameList[element]; ok {
			element = name
		}
		return element + "[]"
	case "character varying":
		if c.CharLength != nil {
			return fmt.Sprintf("varchar(%d)", *c.CharLength)
		}
		return "varchar"
	case "numeric":
		if c.Precision != nil && c.Scale != nil {
			return fmt.Sprintf("numeric(%d,%d)", *c.Precision, *c.Scale)
		}
		return "numeric"
	case "timestamp with time zone":
		return "timestamptz"
	case "timestamp without time zone":
		return "timestamp"
	}
	return c.DataType
}
